"""Encrypt provider credentials before they are written to the database."""

from cryptography.fernet import Fernet, InvalidToken

from app.config import get_settings


class SecretConfigurationError(RuntimeError):
    """Raised when the backend cannot safely encrypt or decrypt a credential."""


def _fernet() -> Fernet:
    key = get_settings().secret_encryption_key
    if not key:
        raise SecretConfigurationError(
            "Set SECRET_ENCRYPTION_KEY before saving or using a database API key"
        )
    try:
        return Fernet(key.encode("ascii"))
    except (ValueError, UnicodeEncodeError) as exc:
        raise SecretConfigurationError(
            "SECRET_ENCRYPTION_KEY must be a Fernet key generated by Fernet.generate_key()"
        ) from exc


def encrypt_secret(value: str) -> str:
    return _fernet().encrypt(value.encode("utf-8")).decode("ascii")


def decrypt_secret(value: str) -> str:
    try:
        return _fernet().decrypt(value.encode("ascii")).decode("utf-8")
    except (InvalidToken, UnicodeEncodeError) as exc:
        raise SecretConfigurationError(
            "Could not decrypt the stored API key; verify SECRET_ENCRYPTION_KEY"
        ) from exc
